from datetime import date

import pytest

from services.schedule_dates import parse_schedule_period


@pytest.mark.parametrize(
    "text,start,end",
    [
        ("рейсы на 2026-11-11", "2026-11-11", "2026-11-11"),
        ("рейсы 11.11.2026", "2026-11-11", "2026-11-11"),
        ("рейсы 11/11/2026", "2026-11-11", "2026-11-11"),
        ("рейсы 11 ноября", "2026-11-11", "2026-11-11"),
        ("рейсы завтра", "2026-11-12", "2026-11-12"),
        ("рейсы послезавтра", "2026-11-13", "2026-11-13"),
        ("рейсы с 16 по 30 ноября", "2026-11-16", "2026-11-30"),
        ("рейсы 16–30 ноября 2027", "2027-11-16", "2027-11-30"),
        ("рейсы на вторую половину ноября дай", "2026-11-16", "2026-11-30"),
        ("рейсы за первую половину ноября", "2026-11-01", "2026-11-15"),
        ("рейсы на весь ноябрь", "2026-11-01", "2026-11-30"),
        ("рейсы за февраль 2028", "2028-02-01", "2028-02-29"),
        ("с 2026-12-25 по 2027-01-05", "2026-12-25", "2027-01-05"),
        ("с 16.11.2026 по 30.11.2026", "2026-11-16", "2026-11-30"),
        ("с 28 ноября по 3 декабря 2027", "2027-11-28", "2027-12-03"),
    ],
)
def test_period(text, start, end):
    period = parse_schedule_period(text, today=date(2026, 11, 11))
    assert period.start.isoformat() == start
    assert period.end.isoformat() == end


@pytest.mark.parametrize(
    "text",
    [
        "рейсы 31 ноября",
        "рейсы 2026-02-29",
        "с 30 по 16 ноября",
        "с 2026-11-01 по 2026-12-02",
        "с 16 ноября",
        "до 30 ноября",
        "11 ноября и 15 ноября",
        "сегодня и завтра",
        "2026-11-01 2026-11-02 2026-11-03",
    ],
)
def test_invalid_period(text):
    with pytest.raises(ValueError):
        parse_schedule_period(text, today=date(2026, 11, 11))


def test_no_period():
    assert parse_schedule_period("покажи рейсы") is None
